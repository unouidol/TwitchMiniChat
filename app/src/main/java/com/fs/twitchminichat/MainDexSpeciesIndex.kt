package com.fs.twitchminichat

import com.fs.twitchminichat.pcg.catalog.PcgPokemonCatalogEntry
import com.fs.twitchminichat.pcg.catalog.PcgPokemonNameNormalizer
import com.fs.twitchminichat.pcg.catalog.PcgVariantKind

/**
 * The category under which the Pokémon Community Game (PCG) main Pokédex lists a species.
 *
 * Each is one filter of the page: "Spawnable", "Starters" and "Legendaries". The three split
 * the 1025 species with no overlap, 822, 81 and 122 when the page was captured on
 * 2026-11-23. Today's Pokédex reading is taken with "Spawnable" alone, so it never lists a
 * [STARTERS] or [LEGENDARIES] species, missing or not.
 */
internal enum class MainDexCategory {
    SPAWNABLE,
    STARTERS,
    LEGENDARIES
}

/**
 * One species of the PCG main Pokédex, as the bundled catalog defines it.
 *
 * @property key normalized species name: the identity compared between a spawn and the
 * stored missing entries.
 * @property name the species' name in tmc-backend's species table ("Nidoran♀", "Unown").
 * @property category the page's category for this species, read from two flags of the
 * catalog entry named after the species: [MainDexCategory.STARTERS] when its `starterFamily`
 * is set, otherwise [MainDexCategory.LEGENDARIES] when its `normallySpawnable` is not, and
 * otherwise [MainDexCategory.SPAWNABLE]. A species without such an entry is a starter when
 * any of its forms is one, and legendary when any is not normally spawnable.
 * `MainDexSpeciesIndexTest` checks the result species by species against the captured page.
 */
internal data class MainDexSpecies(
    val key: String,
    val name: String,
    val category: MainDexCategory
) {
    /**
     * Whether a Spawnable-only Pokédex capture lists this species while it is missing, so
     * that its absence from the capture means it is registered. Only
     * [MainDexCategory.SPAWNABLE] species are: a missing starter or legendary is absent from
     * that capture too.
     */
    val coveredBySpawnableSnapshot: Boolean
        get() = category == MainDexCategory.SPAWNABLE
}

/**
 * Resolves catalog names and stored Pokédex keys to main-Pokédex species.
 *
 * The PCG main Pokédex holds one entry per species, sometimes named after a base form
 * ("Vivillon (Meadow)", "Unown (A)"), and catching any form registers the species. The
 * stored Pokédex snapshot keeps normalized keys only, with the parentheses lost, so a name
 * resolves by these rules, in order:
 *
 * 1. a catalog name resolves to that name's species ("gal mr mime" to Mr. Mime);
 * 2. any other name resolves to the longest species name it equals or starts with,
 *    followed by a space ("vivillon meadow" to Vivillon, "unown" to Unown);
 * 3. a name that neither rule places has no species, and matches nothing.
 *
 * Rule 1 comes first so that a catalog name is never cut at a shorter species: "porygon z"
 * is Porygon-Z, not Porygon.
 *
 * A species is the catalog's `sourceSpecies` without `-Alola`, `-Galar`, `-Hisui` or
 * `-Paldea`, named after its ordinary entry when it has one ("Nidoran-F" is "Nidoran♀").
 * tmc-backend's `main_dex_species_table_v1.json`, which the missing-Dex alerts match with,
 * is generated by the same rule; `MainDexSpeciesIndexTest` keeps the two equal name by
 * name, so that the Smart Catch panel and the alerts agree.
 */
internal class MainDexSpeciesIndex private constructor(
    private val speciesByCatalogKey: Map<String, MainDexSpecies>,
    private val speciesByKey: Map<String, MainDexSpecies>
) {

    /** Every species, in catalog order. */
    val species: Collection<MainDexSpecies>
        get() = speciesByKey.values

    /** Species of a catalog name (rule 1 only); null when [name] is not a catalog name. */
    fun speciesOfCatalogName(name: String): MainDexSpecies? {
        return speciesByCatalogKey[PcgPokemonNameNormalizer.normalize(name)]
    }

    /** Species of any name or stored key, by the rules above; null when none applies. */
    fun speciesOf(name: String): MainDexSpecies? {
        val key = PcgPokemonNameNormalizer.normalize(name)
        if (key.isBlank()) return null

        return speciesByCatalogKey[key]
            ?: speciesByKey[key]
            ?: longestSpeciesPrefix(key)
    }

    /** A normalized key is single-spaced, so each word boundary is one candidate prefix. */
    private fun longestSpeciesPrefix(key: String): MainDexSpecies? {
        var end = key.lastIndexOf(' ')
        while (end > 0) {
            speciesByKey[key.substring(0, end)]?.let { species -> return species }
            end = key.lastIndexOf(' ', end - 1)
        }
        return null
    }

    companion object {

        /**
         * Names every species of the catalog: its ordinary entry's name, or the cleaned
         * `sourceSpecies` when it has none.
         *
         * Never fails, so that a catalog [build] refuses still loads for spawn resolution.
         */
        fun speciesNames(entries: List<PcgPokemonCatalogEntry>): Map<String, String> {
            return entries
                .groupBy { entry -> cleanSourceSpecies(entry.sourceSpecies) }
                .mapValues { (speciesId, speciesEntries) ->
                    speciesEntries
                        .firstOrNull { entry -> entry.variantKind == PcgVariantKind.NONE }
                        ?.displayName
                        ?: speciesId
                }
        }

        /**
         * Builds the index once per catalog load, from entries named by [speciesNames].
         *
         * Fails on a catalog that would make a name ambiguous: two species with one
         * normalized name, or a catalog name equal to another species' name.
         */
        fun build(entries: List<PokemonTypeEntry>): MainDexSpeciesIndex {
            require(entries.isNotEmpty()) { "The PCG catalog is empty" }

            val entryByKey = entries.associateBy(PokemonTypeEntry::sourceKey)
            val formsBySpeciesKey = entries.groupBy { entry ->
                PcgPokemonNameNormalizer.normalize(entry.mainDexSpecies)
            }

            val speciesByKey = LinkedHashMap<String, MainDexSpecies>()
            formsBySpeciesKey.forEach { (key, forms) ->
                require(key.isNotBlank()) { "A species has a blank name" }
                val names = forms.mapTo(LinkedHashSet(), PokemonTypeEntry::mainDexSpecies)
                require(names.size == 1) { "Two species share one normalized name" }

                // The catalog entry named after the species is its ordinary entry.
                val ordinaryEntry = entryByKey[key]
                require(ordinaryEntry == null || ordinaryEntry in forms) {
                    "A catalog name is another species' name"
                }

                speciesByKey[key] = MainDexSpecies(
                    key = key,
                    name = names.single(),
                    category = categoryOf(ordinaryEntry?.let(::listOf) ?: forms)
                )
            }

            val speciesByCatalogKey = entries.associateTo(LinkedHashMap()) { entry ->
                entry.sourceKey to speciesByKey.getValue(
                    PcgPokemonNameNormalizer.normalize(entry.mainDexSpecies)
                )
            }

            return MainDexSpeciesIndex(
                speciesByCatalogKey = speciesByCatalogKey,
                speciesByKey = speciesByKey
            )
        }

        /**
         * Category from the entries that carry a species' flags: its ordinary entry alone,
         * or every form when it has none. Either doubt leaves the species out of
         * [MainDexCategory.SPAWNABLE], so that no absence is ever read as registered.
         */
        private fun categoryOf(flagEntries: List<PokemonTypeEntry>): MainDexCategory {
            return when {
                flagEntries.any(PokemonTypeEntry::starterFamily) -> MainDexCategory.STARTERS
                !flagEntries.all(PokemonTypeEntry::normallySpawnable) -> MainDexCategory.LEGENDARIES
                else -> MainDexCategory.SPAWNABLE
            }
        }

        /** The catalog's source species without its regional suffix ("Marowak-Alola" to "Marowak"). */
        fun cleanSourceSpecies(sourceSpecies: String): String {
            return sourceSpecies.replace(REGIONAL_SOURCE_SUFFIX, "")
        }

        /** The regional suffixes that tmc-backend's table generator strips, the same four. */
        private val REGIONAL_SOURCE_SUFFIX = Regex("-(?:Alola|Galar|Hisui|Paldea)$")
    }
}
